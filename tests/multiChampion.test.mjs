import assert from "node:assert/strict";
import {CHAMPIONS,CHAMPION_BY_NAME} from "../src/data/champions.js";
import {OFFICIAL_ROSTER,ROSTER_SOURCE} from "../src/data/officialRoster.js";
import {BUILD_REFERENCES,getBuildReference} from "../src/data/buildReferences.js";
import {PATCH_CHANGES,patchChangeForChampion,patchChangesForItems,patchChangesForRunes} from "../src/data/patchNotes.js";
import {ROLES,createDraft,analyzeComposition,championRecommendation} from "../src/core/multiChampion.js";
import {TACTICAL_PROFILES,tacticalProfile} from "../src/data/tacticalProfiles.js";

assert.equal(CHAMPIONS.length,142,"El selector debe coincidir con el roster oficial 7.3b.");
assert.equal(OFFICIAL_ROSTER.length,142);
assert.equal(new Set(OFFICIAL_ROSTER.map(x=>x.name)).size,142);
assert.equal(new Set(OFFICIAL_ROSTER.map(x=>x.slug)).size,142);
assert(OFFICIAL_ROSTER.every(x=>CHAMPIONS.some(c=>c.name===x.name)),"No debe haber fichas ajenas al roster oficial");
assert.equal(ROSTER_SOURCE.patch,"7.3b");
for(const n of ["K\x27Sante","Mel","Nidalee","Norra","Rell","Skarner","Smolder","Taliyah","Vel\x27Koz"])assert(CHAMPIONS.some(c=>c.name===n),"Campeón oficial ausente "+n);
for(const n of ["Elise","LeBlanc","Malzahar","Neeko","Qiyana"])assert(!CHAMPIONS.some(c=>c.name===n),"Campeón no listado por Riot "+n);
assert.equal(CHAMPIONS.find(c=>c.name==="Norra").quality,"unclassified");
assert.equal(new Set(CHAMPIONS.map(c=>c.name)).size,CHAMPIONS.length);
assert.equal(ROLES.length,5,"Hay que incluir los cinco roles.");
const base={champion:"Camille",role:"baron",allies:["Jarvan IV","Orianna","Jinx","Braum"],enemies:["Gwen","Viego","Brand","Lucian","Lux"]};
const draft=createDraft(base);
const analysis=analyzeComposition(draft,CHAMPION_BY_NAME);
assert.equal(analysis.enemyLane,"Gwen");
assert.equal(analysis.coverage.complete,true);
assert.equal(analysis.composition.magic,3);
assert.equal(analysis.composition.physical,2);
assert.equal(analysis.role,"baron");
assert.equal(championRecommendation(draft).status,"unverified","Nunca simular build verificada.");
for(const role of ROLES){
  const profile=createDraft({...base,role});
  assert.equal(analyzeComposition(profile,CHAMPION_BY_NAME).role,role);
}
assert.throws(()=>createDraft({...base,champion:"Gwen"}),/repetirse/);
assert.throws(()=>createDraft({...base,allies:["Gwen"]}),/repetirse/);
assert.throws(()=>createDraft({...base,enemies:["Gwen","Gwen"]}),/repetirse/);
assert.throws(()=>createDraft({...base,role:"invalid"}),/posición/);
assert.throws(()=>createDraft({...base,champion:""}),/campeón/);
assert.throws(()=>analyzeComposition(createDraft({...base,enemies:["Fantasma"]}),CHAMPION_BY_NAME),/fuera del catálogo/);
const newChamp=analyzeComposition(createDraft({...base,enemies:["Norra"]}),CHAMPION_BY_NAME);
assert.equal(newChamp.composition.unclassified,1);
assert.equal(newChamp.composition.control,"PARCIAL");
assert(newChamp.advice.warnings.some(x=>x.includes("clasificación")));
const partial=analyzeComposition(createDraft({...base,enemies:["Gwen"]}),CHAMPION_BY_NAME);
assert.equal(partial.coverage.complete,false);
assert(partial.advice.warnings.some(x=>x.includes("parcial")));
const known={camille:{roles:["baron"],patch:"7.3b",source:"https://example.com/verified"}};
assert.equal(championRecommendation(draft,known).status,"verified");
assert.equal(championRecommendation(createDraft({...base,role:"mid"}),known).status,"unverified");
assert(Object.keys(TACTICAL_PROFILES).length>=10);
assert.equal(tacticalProfile("Camille","baron")?.status,"editorial");
assert.equal(tacticalProfile("Lee Sin","jungle")?.status,"editorial");
assert.equal(tacticalProfile("Jinx","dragon")?.status,"editorial");
assert.equal(tacticalProfile("Jinx","baron"),null,"Off-role no presenta perfil como verificado.");
assert.equal(tacticalProfile("Desconocido","baron"),null);
assert.equal(BUILD_REFERENCES.length,12);
assert.equal(new Set(BUILD_REFERENCES.map(x=>x.champion+"|"+x.role)).size,BUILD_REFERENCES.length);
for(const b of BUILD_REFERENCES){
  const a=getBuildReference(b.champion,b.role);
  assert.equal(a.status,"referenced",b.champion+" "+b.role);
  assert.equal(a.reference.patch,"7.3b");
  assert.equal(a.reference.runes.length,5);
  assert.equal(a.reference.spells.length,2);
  assert(a.reference.finalItems.length>=5);
  assert.equal(getBuildReference(b.champion,b.role,"7.4").status,"stale");
}
const akaliMid=getBuildReference("Akali","mid");
const akaliBaron=getBuildReference("Akali","baron");
assert.equal(akaliMid.status,"referenced");
assert.equal(akaliBaron.status,"referenced");
assert.deepEqual(akaliMid.reference.runes,["Electrocute","Sudden Impact","Chain Assault","Eyeball Collector","Second Wind"]);
assert.deepEqual(akaliBaron.reference.runes,["Fleet Footwork","Sudden Impact","Chain Assault","Eyeball Collector","Second Wind"]);
assert.equal(akaliMid.reference.finalItems.length,6);
assert.equal(akaliMid.reference.source.url,"https://www.wildriftfire.com/guide/akali");
assert.equal(akaliMid.reference.skillPriorityStatus,"pending_review");
assert.equal(tacticalProfile("Akali","mid")?.status,"editorial");
assert.equal(tacticalProfile("Akali","baron")?.status,"editorial");
assert(tacticalProfile("Akali","mid")?.matchups?.Brand.includes("Sear"));
assert.equal(getBuildReference("Norra","mid").status,"missing");
assert.equal(getBuildReference("Camille","mid").status,"missing");
assert.equal(PATCH_CHANGES.patch,"7.3b");
assert.equal(Object.keys(PATCH_CHANGES.champions).length,8);
assert.equal(PATCH_CHANGES.items.length,6);
assert.equal(PATCH_CHANGES.runes.length,4);
assert.equal(patchChangeForChampion("Yasuo").direction,"buff");
assert.equal(patchChangeForChampion("Senna").direction,"nerf");
assert.equal(patchChangeForChampion("Camille"),null);
assert(patchChangesForItems(["Thornmail"]).some(x=>x.name==="Thornmail"));
assert(patchChangesForRunes(["Grasp of the Undying"]).length===1);
console.log("PASS: 142 campeones oficiales, 5 roles, composición, faltantes, duplicados, evidencia.");
